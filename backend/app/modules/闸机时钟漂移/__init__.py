"""闸机时钟漂移：负历时裁决主链。

闸机时钟回拨会让出站事件时早于进站事件时（负历时）。负历时是异常数据关系，
裁决与写库必须同成败：先原子占位开腿（状态迁移守卫），再在同一事务里落
行程或旁路，并发下不得旁路与行程双落。

全局唯一口径（关键设计取舍，二选一后全站贯彻）：**漂移秒吸收（乙）**。
- 出站事件时 ≥ 进站事件时：正历时，走成对 happy path，本模块不介入。
- 负历时绝对值 ≤ 站规「漂移秒」：成对吸收——写行程（历时按 0）并写漂移审计，
  开腿与进出站刷卡同票「已成对」。
- 负历时绝对值 > 漂移秒：拒配旁路——开腿与进出站刷卡同票「已旁路」，不写行程。

与被否决的甲口径（任何负历时即旁路、不写行程）的分叉点：「出站比进站早 10 秒
且漂移秒=30」在乙口径下有行程（成对吸收），在甲口径下无行程。只读接口
``裁决`` 返回的 ``口径`` 与 ``命运`` 字段可把两种口径区分开。

``valid`` 语义：该裁决是否产出可落账的有效行程（正历时成对 / 成对吸收为
True；旁路 / 不可裁决为 False）。
"""

import json

from app.services import 时间, 配对

NAME = "闸机时钟漂移"

口径 = "漂移秒吸收"

默认漂移秒 = 30

# 命运取值
正历时成对 = "正历时成对"
成对吸收 = "成对吸收"
旁路 = "旁路"
不可裁决 = "不可裁决"

旁路原因 = "负历时超漂移"


class 裁决冲突(Exception):
    """开腿在裁决前已被并发事务改写——裁决与写库同成败，整批回滚。"""


def 取漂移秒(站规: dict) -> int:
    try:
        return int((站规 or {}).get("漂移秒", 默认漂移秒))
    except (TypeError, ValueError):
        return 默认漂移秒


def 裁决(进站事件时: str, 出站事件时: str, 漂移值: int) -> dict:
    """只读裁决：给进站/出站事件时，给出命运，不写库。

    返回字段：进站时 / 出站时 / 负历时秒 / 漂移秒 / 口径 / 命运 / valid。
    """
    漂移秒 = 取漂移秒({"漂移秒": 漂移值})
    基 = {
        "进站时": 进站事件时,
        "出站时": 出站事件时,
        "漂移秒": 漂移秒,
        "口径": 口径,
    }
    try:
        历时 = 时间.差秒(进站事件时, 出站事件时)
    except Exception:
        return {**基, "负历时秒": None, "命运": 不可裁决, "valid": False}
    if 历时 >= 0:
        return {**基, "负历时秒": 0, "命运": 正历时成对, "valid": True}
    负 = -历时
    if 负 <= 漂移秒:
        return {**基, "负历时秒": 负, "命运": 成对吸收, "valid": True}
    return {**基, "负历时秒": 负, "命运": 旁路, "valid": False}


def 落账(conn, 开腿, 出站事件编号: str, 出站站点键: str, 出站事件时: str,
        处理时: str, 漂移秒: int) -> dict:
    """负历时裁决 + 写库，同成败。调用方持有事务（与本批其它写同 commit）。

    返回 {命运, 裁决, 行程键?}；并发占位失败抛 裁决冲突，整批回滚，绝不双落。
    """
    裁 = 裁决(开腿["进站事件时"], 出站事件时, 漂移秒)
    if 裁["命运"] == 不可裁决:
        raise ValueError(f"负历时裁决入参不可裁决: {裁}")
    if 裁["命运"] == 正历时成对:
        raise ValueError("正历时应走成对 happy path，不应进入漂移落账")

    if 裁["命运"] == 成对吸收:
        if not 配对.占位开腿(conn, 开腿["开腿键"], "已成对", 处理时):
            raise 裁决冲突(f"开腿{开腿['开腿键']}已被并发裁决")
        行程键 = f"行-{开腿['进站事件编号']}-{出站事件编号}"
        conn.execute(
            """INSERT INTO 行程账(行程键,卡号,进站事件编号,出站事件编号,进站站点键,出站站点键,
               进站事件时,出站事件时,历时秒,状态,版本,处理时)
               VALUES (?,?,?,?,?,?,?,?,0,'已成对',1,?)""",
            (
                行程键,
                开腿["卡号"],
                开腿["进站事件编号"],
                出站事件编号,
                开腿["进站站点键"],
                出站站点键,
                开腿["进站事件时"],
                出站事件时,
                处理时,
            ),
        )
        conn.execute(
            """INSERT INTO 漂移审计(行程键,卡号,进站事件编号,出站事件编号,
               进站事件时,出站事件时,负历时秒,漂移秒,口径,命运,时刻)
               VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
            (
                行程键,
                开腿["卡号"],
                开腿["进站事件编号"],
                出站事件编号,
                开腿["进站事件时"],
                出站事件时,
                裁["负历时秒"],
                裁["漂移秒"],
                口径,
                成对吸收,
                处理时,
            ),
        )
        conn.execute(
            "UPDATE 刷卡点 SET 命运=?, 行程键=? WHERE 事件编号 IN (?,?)",
            ("已成对", 行程键, 开腿["进站事件编号"], 出站事件编号),
        )
        return {"命运": 成对吸收, "行程键": 行程键, "裁决": 裁}

    # 旁路：开腿与进出站刷卡同票已旁路，不写行程
    if not 配对.占位开腿(conn, 开腿["开腿键"], "已旁路", 处理时):
        raise 裁决冲突(f"开腿{开腿['开腿键']}已被并发裁决")
    conn.execute(
        "UPDATE 刷卡点 SET 命运=? WHERE 事件编号 IN (?,?)",
        ("已旁路", 开腿["进站事件编号"], 出站事件编号),
    )
    conn.execute(
        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
        (
            旁路原因,
            开腿["卡号"],
            出站事件编号,
            json.dumps(
                {
                    "开腿键": 开腿["开腿键"],
                    "进站事件编号": 开腿["进站事件编号"],
                    "出站事件编号": 出站事件编号,
                    "进站时": 裁["进站时"],
                    "出站时": 裁["出站时"],
                    "负历时秒": 裁["负历时秒"],
                    "漂移秒": 裁["漂移秒"],
                    "口径": 口径,
                },
                ensure_ascii=False,
            ),
            处理时,
        ),
    )
    return {"命运": 旁路, "裁决": 裁}
